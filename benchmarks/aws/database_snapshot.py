"""Cold, exact-image PostgreSQL benchmark snapshots. Run on the Docker host."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time
import uuid


def run(*args):
    return subprocess.check_output(args, text=True).strip()


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def inspect(kind, name):
    return json.loads(run('docker', kind, 'inspect', name))[0]


def sql(container, statement):
    return run('docker', 'exec', container, 'psql', '-XqAt', '-U', 'postgres', '-d', 'benchmark', '-v', 'ON_ERROR_STOP=1', '-c', statement)


def fingerprint(container):
    # Capture stable logical/physical properties, excluding volatile transaction counters.
    return json.loads(sql(container, """SELECT json_build_object(
      'version',current_setting('server_version'),
      'rows',(SELECT count(*) FROM documents),
      'extensions',(SELECT json_object_agg(extname,extversion) FROM pg_extension),
      'relations',(SELECT json_object_agg(relname,pg_relation_size(oid)) FROM pg_class WHERE relname IN ('documents','documents_idx')),
      'visibility',(SELECT row_to_json(v) FROM pg_visibility_map_summary('documents') v),
      'segments',(SELECT json_agg(s) FROM stannum.segment_info('documents_idx') s),
      'sample',(SELECT md5(string_agg(ctid::text || ':' || id || ':' || md5(body),',' ORDER BY ctid)) FROM (SELECT ctid,id,body FROM documents LIMIT 1000) d),
      'probe',(SELECT count(*) FROM documents WHERE body ==> 'database'))"""))


def verify_files(folder, manifest):
    if manifest.get('format') != 1 or manifest.get('state') != 'restore-verified':
        raise ValueError('Snapshot is not a verified supported format')
    if set(manifest['files']) != {'database.tar.gz', 'image.tar.gz'}:
        raise ValueError('Unexpected snapshot files')
    for name, entry in manifest['files'].items():
        path=folder/name
        if path.stat().st_size != entry['bytes'] or digest(path) != entry['sha256']:
            raise ValueError('Snapshot checksum mismatch: '+name)


def empty_volume(name):
    # Never replace, empty, or mount an existing volume on restore.
    result=subprocess.run(['docker','volume','inspect',name],capture_output=True)
    if result.returncode == 0:
        raise ValueError('Restore requires a new volume: '+name)
    run('docker','volume','create',name)
    return Path(inspect('volume',name)['Mountpoint'])


def restore(folder, manifest, volume):
    verify_files(folder,manifest)
    run('docker','load','-i',str(folder/'image.tar.gz'))
    image=inspect('image',manifest['image_id'])
    if image['Architecture'] != manifest['architecture']:
        raise ValueError('Image architecture mismatch')
    target=empty_volume(volume)
    try:
        # Archives are generated by this tool, authenticated by the manifest hash.
        # Reject external links before handing the archive to privileged tar.
        import tarfile
        with tarfile.open(folder/'database.tar.gz') as archive:
            for member in archive:
                parts=Path(member.name).parts
                if member.name.startswith('/') or '..' in parts or not (member.isfile() or member.isdir()):
                    raise ValueError('Unsafe database archive member: '+member.name)
        run('tar','-xzf',str(folder/'database.tar.gz'),'-C',str(target))
    except BaseException:
        run('docker','volume','rm',volume)
        raise


def validate(folder, manifest):
    volume='stannum-snapshot-check-'+uuid.uuid4().hex[:12]
    container=volume
    started=time.monotonic()
    restore(folder,manifest,volume)
    try:
        run('docker','run','-d','--name',container,'--network','none','--cpus','4','--memory','4g',
            '-v',volume+':/var/lib/postgresql',manifest['image_id'],
            'postgres','-c','shared_buffers=1GB','-c','autovacuum=off','-c','jit=off')
        deadline=time.monotonic()+120
        while subprocess.run(['docker','exec',container,'pg_isready','-U','postgres','-d','benchmark'],capture_output=True).returncode:
            if time.monotonic()>deadline:raise RuntimeError('Restored database did not start')
            time.sleep(1)
        actual=fingerprint(container)
        if actual != manifest['fingerprint']:
            (folder/'restore-mismatch.json').write_text(json.dumps(actual,indent=2))
            raise ValueError('Restored database fingerprint differs')
        return time.monotonic()-started
    finally:
        subprocess.run(['docker','rm','-f',container],capture_output=True)
        run('docker','volume','rm',volume)


def capture(args):
    folder=args.directory
    folder.mkdir(parents=True,exist_ok=False)
    started=time.monotonic()
    info=inspect('container',args.container)
    mounts=[m for m in info['Mounts'] if m['Destination']=='/var/lib/postgresql' and m['Type']=='volume']
    if len(mounts)!=1 or not info['State']['Running']:
        raise ValueError('Expected one running benchmark container with a named PG volume')
    mount=mounts[0]; source=Path(mount['Source'])
    users=run('docker','ps','-q','--filter','volume='+mount['Name']).splitlines()
    if len(users)!=1:raise ValueError('Volume has other active users')
    # Refuse external tablespaces/symlinks; the whole cluster must be inside the volume.
    if any(p.is_symlink() for p in source.rglob('*')):
        raise ValueError('External/symbolic links are not supported')
    sql(args.container,'VACUUM ANALYZE documents')
    sql(args.container,'CHECKPOINT')
    baseline=fingerprint(args.container)
    image=inspect('image',info['Image'])
    manifest=dict(format=1,state='restore-verified',image_id=info['Image'],architecture=image['Architecture'],
                  source_commit=args.source_commit,corpus_sha256=args.corpus_sha256,
                  created_utc=time.strftime('%Y-%m-%dT%H:%M:%SZ',time.gmtime()),fingerprint=baseline,files={})
    # docker stop uses the image's stop signal; require a successful clean exit.
    run('docker','stop','--time','300',args.container)
    try:
        stopped=inspect('container',args.container)['State']
        if stopped['Running'] or stopped['ExitCode']!=0:raise ValueError('PostgreSQL did not stop cleanly')
        pgdata=next(v.split('=',1)[1] for v in info['Config']['Env'] if v.startswith('PGDATA='))
        control=run('docker','run','--rm','--network','none','-e','LC_ALL=C','-v',mount['Name']+':/var/lib/postgresql:ro',
                    '--entrypoint','/usr/lib/postgresql/18/bin/pg_controldata',info['Image'],pgdata)
        if not any(line.split(':',1)[-1].strip()=='shut down' for line in control.splitlines() if line.startswith('Database cluster state:')):
            raise ValueError('pg_control does not confirm clean shutdown')
        (folder/'pg_controldata.txt').write_text(control+'\n')
        run('tar','-I','gzip -1','-cf',str(folder/'database.tar.gz'),'-C',str(source),'.')
    finally:
        run('docker','start',args.container)
    # Image bytes are retained so a future restore never relies on rebuilding an identical image.
    with (folder/'image.tar.gz').open('wb') as output:
        save=subprocess.Popen(['docker','save',info['Image']],stdout=subprocess.PIPE)
        compress=subprocess.run(['gzip','-1'],stdin=save.stdout,stdout=output)
        save.stdout.close()
        if save.wait()!=0 or compress.returncode!=0:raise RuntimeError('Image export failed')
    for name in ('database.tar.gz','image.tar.gz'):
        path=folder/name;manifest['files'][name]=dict(bytes=path.stat().st_size,sha256=digest(path))
    manifest['capture_seconds']=time.monotonic()-started
    manifest['restore_verify_seconds']=validate(folder,manifest)
    # Only publish a completion marker after a real startup and content comparison.
    (folder/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest),flush=True)


def transfer(args):
    import boto3
    s3=boto3.client('s3');started=time.monotonic()
    prefix=args.prefix.rstrip('/')+'/'
    if not prefix.startswith('postgres-snapshots/'):
        raise ValueError('Use the dedicated postgres-snapshots/ prefix')
    if args.command=='publish':
        manifest=json.loads((args.directory/'manifest.json').read_text())
        verify_files(args.directory,manifest)
        # Prefix-scoped listing avoids HeadObject's unscoped ListBucket requirement
        # for distinguishing an absent key from access denied.
        existing=s3.list_objects_v2(Bucket=args.bucket,Prefix=prefix,MaxKeys=1)
        if existing.get('KeyCount',0):raise ValueError('Snapshot prefix already exists; choose a new prefix')
        for name in manifest['files']:
            s3.upload_file(str(args.directory/name),args.bucket,prefix+name)
        manifest['upload_seconds']=time.monotonic()-started
        manifest['s3']=dict(bucket=args.bucket,prefix=prefix)
        s3.put_object(Bucket=args.bucket,Key=prefix+'manifest.json',Body=(json.dumps(manifest,indent=2)+'\n').encode())
        (args.directory/'published.json').write_text(json.dumps(manifest,indent=2)+'\n')
    else:
        args.directory.mkdir(parents=True,exist_ok=False)
        manifest=json.loads(s3.get_object(Bucket=args.bucket,Key=prefix+'manifest.json')['Body'].read())
        if manifest.get('format')!=1 or manifest.get('state')!='restore-verified' or set(manifest['files'])!={'database.tar.gz','image.tar.gz'}:
            raise ValueError('Unsupported snapshot manifest')
        for name in manifest['files']:
            s3.download_file(args.bucket,prefix+name,str(args.directory/name))
        verify_files(args.directory,manifest)
        (args.directory/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
        (args.directory/'download.json').write_text(json.dumps(dict(seconds=time.monotonic()-started))+'\n')
    print(json.dumps(manifest),flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    commands=parser.add_subparsers(dest='command',required=True)
    c=commands.add_parser('capture');c.add_argument('--container',required=True)
    c.add_argument('--source-commit',required=True);c.add_argument('--corpus-sha256',required=True)
    c.add_argument('--directory',type=Path,required=True)
    r=commands.add_parser('restore');r.add_argument('--directory',type=Path,required=True);r.add_argument('--volume',required=True)
    r.add_argument('--corpus-sha256',required=True)
    v=commands.add_parser('check');v.add_argument('--directory',type=Path,required=True);v.add_argument('--container',required=True)
    for name in ('publish','fetch'):
        t=commands.add_parser(name);t.add_argument('--directory',type=Path,required=True)
        t.add_argument('--bucket',required=True);t.add_argument('--prefix',required=True)
    args=parser.parse_args()
    if args.command=='capture':capture(args)
    elif args.command in ('publish','fetch'):transfer(args)
    elif args.command=='check':
        manifest=json.loads((args.directory/'manifest.json').read_text())
        if inspect('container',args.container)['Image']!=manifest['image_id']:raise ValueError('Wrong runtime image')
        if fingerprint(args.container)!=manifest['fingerprint']:raise ValueError('Restored content differs')
        print('Restored database matches snapshot')
    else:
        manifest=json.loads((args.directory/'manifest.json').read_text())
        if manifest['corpus_sha256']!=args.corpus_sha256:raise ValueError('Wrong corpus')
        restore(args.directory,manifest,args.volume)
        print(json.dumps(dict(volume=args.volume,image_id=manifest['image_id'])))


if __name__=='__main__':main()
